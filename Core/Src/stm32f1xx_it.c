/**
  * @brief  USART2 全局中断：接收 ESP8266 返回的数据
  */
void USART2_IRQHandler(void)
{
  /* USER CODE BEGIN USART2_IRQn 0 */
  /* 只做寄存器级接收：读 DR 会同时清除 RXNE 和 ORE。
     不要在这里再调 HAL_UART_IRQHandler()：
       - 本工程未使用 HAL 的接收 API（pRxBuffPtr 为 NULL）；
       - 一旦 ORE（溢出）被置位，HAL 会调用 UART_EndRxTransfer() 关闭 RXNE 中断，
         导致 ESP8266 接收永久失效，后续所有 AT 命令都超时 → 看起来就是“卡死”。 */
  if(__HAL_UART_GET_FLAG(&huart2, UART_FLAG_RXNE) != RESET ||
     __HAL_UART_GET_FLAG(&huart2, UART_FLAG_ORE)  != RESET)
  {
    uint8_t rx = (uint8_t)(huart2.Instance->DR & 0xFF);
    if(esp8266_cnt < sizeof(esp8266_buf))
    {
      esp8266_buf[esp8266_cnt++] = rx;
    }
    else
    {
      esp8266_cnt = 0;
      esp8266_buf[esp8266_cnt++] = rx;
    }
  }
  /* USER CODE END USART2_IRQn 0 */
  /* USER CODE BEGIN USART2_IRQn 1 */

  /* USER CODE END USART2_IRQn 1 */
}

/**
  * @brief  USART3 全局中断：接收 GY-NEO6MV2 GPS 模块的 NMEA 数据
  */
void USART3_IRQHandler(void)
{
  /* USER CODE BEGIN USART3_IRQn 0 */
  /* 与 USART2 同样做法：只做寄存器级接收，不调 HAL_UART_IRQHandler()，
     避免 ORE 触发 HAL 的 UART_EndRxTransfer() 把 RXNE 中断关掉。 */
  if(__HAL_UART_GET_FLAG(&huart3, UART_FLAG_RXNE) != RESET ||
     __HAL_UART_GET_FLAG(&huart3, UART_FLAG_ORE)  != RESET)
  {
    uint8_t rx = (uint8_t)(huart3.Instance->DR & 0xFF);
    /* 统一交给路由器：按帧首在 GPS($) 与 JW01(0xFF) 之间自动分流 */
    JW01_RouteByte(rx);
  }
  /* USER CODE END USART3_IRQn 0 */
  /* USER CODE BEGIN USART3_IRQn 1 */

  /* USER CODE END USART3_IRQn 1 */
}

