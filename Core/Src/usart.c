/**
  * @brief  串口阻塞发送（寄存器方式，供 ESP8266 等使用）
  */
void Usart_SendString(USART_TypeDef *USARTx, unsigned char *str, unsigned short len)
{
  unsigned short count = 0;

  for(; count < len; count++)
  {
    while((USARTx->SR & 0x40) == 0);
    USARTx->DR = str[count];
  }
}

/**
  * @brief  调试打印：格式化后通过 USB 虚拟串口(CDC)输出
  * @note   为兼容原有 UsartPrintf(USART_DEBUG, ...) 调用而保留原函数签名，
  *         USARTx 参数不再使用，实际输出走 USB CDC。
  *         使用静态发送缓冲区，并等待上一次 USB 发送完成，避免发送中数据被覆盖。
  */
void UsartPrintf(USART_TypeDef *USARTx, char *fmt, ...)
{
  static char cdc_buf[256];                 /* 静态缓冲区：USB 异步发送期间必须保持有效 */
  USBD_CDC_HandleTypeDef *hcdc;
  va_list ap;
  int len;
  uint32_t t0;
  uint8_t retry = 0;

  (void)USARTx;

  /* 等待上一次发送完成，防止覆盖正在被 USB 读取的数据 */
  hcdc = (USBD_CDC_HandleTypeDef *)hUsbDeviceFS.pClassData;
  t0 = HAL_GetTick();
  while(hcdc != NULL && hcdc->TxState != 0)
  {
    if(HAL_GetTick() - t0 > 100)
      break;
    HAL_Delay(1);
  }

  va_start(ap, fmt);
  len = vsnprintf(cdc_buf, sizeof(cdc_buf), fmt, ap);
  va_end(ap);

  if(len <= 0)
    return;
  if(len > (int)sizeof(cdc_buf) - 1)
    len = (int)sizeof(cdc_buf) - 1;

  while(CDC_Transmit_FS((uint8_t *)cdc_buf, (uint16_t)len) == USBD_BUSY && retry++ < 50)
  {
    HAL_Delay(1);
  }
}

